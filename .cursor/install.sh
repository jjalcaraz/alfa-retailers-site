#!/usr/bin/env bash
# Idempotent repository bootstrap for the Alfa Retailers Next.js app.
# Runs after the repository is checked out. Installs Node dependencies and
# generates a local dev env file. PostgreSQL is provided by the base image
# (installed once at setup) and is started per-boot by start.sh.
set -euo pipefail

cd "$(dirname "$0")/.."

# Ensure PostgreSQL is present in the base image. Installing here is idempotent:
# apt-get is a no-op when the packages are already installed (e.g. from the snapshot).
if ! command -v pg_ctlcluster >/dev/null 2>&1; then
  echo "Installing PostgreSQL..."
  sudo apt-get update -qq
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq postgresql postgresql-contrib
fi

# Create a local dev environment file if one is not already present.
# .env is read by both the Prisma CLI and Next.js. It is gitignored.
if [ ! -f .env ]; then
  echo "Creating .env for local development..."
  cat > .env <<'ENV'
# Local development environment (Cloud Agent). Auto-generated by .cursor/install.sh.
DATABASE_URL="postgresql://alfa:alfa@127.0.0.1:5432/alfaretailers?sslmode=disable"

NEXTAUTH_SECRET="dev-only-secret-do-not-use-in-production"
NEXTAUTH_URL="http://localhost:3000"

NODE_ENV="development"
PORT="3000"

NEXT_PUBLIC_SITE_URL="http://localhost:3000"
NEXT_PUBLIC_SITE_NAME="Alfa Retailers"
NEXT_PUBLIC_SITE_DESCRIPTION="Convert your stagnant long-term rental into a profitable short-term rental."

# Contact form safeguards (local dev values)
CONTACT_ALLOWED_ORIGINS="http://localhost:3000"
CONTACT_FORM_TOKEN_SECRET="dev-only-contact-form-token-secret"
CONTACT_EMAIL_QUEUE_MODE="sync"
ENABLE_ANALYTICS="false"
ENABLE_EMAIL_NOTIFICATIONS="false"
ENV
fi

# Install Node dependencies. postinstall runs `prisma generate`.
npm ci

echo "install.sh complete."
